import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/xiyuan-salt-museum.md','utf8').split('---')[1]);
test('Xiyuan separates dated museum records and unverified access',async({page})=>{
 await page.goto('/attractions/xiyuan-salt-museum/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('article.article-body a[href="https://www.google.com/maps/place/Xi+Yuan+Yan+Chang+Di+Fang+Cultural+Guan/@24.5088409,118.402999,861m/data=!3m2!1e3!4b1!4m6!3m5!1s0x3414bb706b9d7db9:0x436a461324f215ff!8m2!3d24.508836!4d118.4055793!16s%2Fg%2F1tp05qsb"]')).toBeVisible();
 await expect(page.locator('article.article-body')).toContainText('具名點位身份已核');
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/xiyuan-salt-museum/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索西園鹽場地方文化館','關於西園鹽場地方文化館','基本資料','交通方式','路線地圖','鹽業歷史與展示改造','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('金門縣文化局');
 await expect(page.locator('.article-body')).toContainText('觀光署原始資料2025年5月22日版均列西園1號');
 await expect(page.locator('.article-body')).toContainText('歷史12號記錄差異原因仍未確認');
 expect(data.locationDescription).toContain('觀光網/觀光署2025-05-22版列西園1號');
 await expect(page.locator('.article-body')).toContainText('2025年5月22日版列免費');
 await expect(page.locator('.article-body')).toContainText('不據此推定收費');
 expect(data.admission).toContain('免費欄null/費用空白');
 await expect(page.locator('.article-body')).toContainText('西園里西園12號');
 await expect(page.locator('.article-body')).toContainText('2026年3月4日');
 await expect(page.locator('.article-body')).toContainText('不是今日開門確認');
 await expect(page.locator('.article-body')).toContainText('不把承攬商當現行全面營運者');
 await expect(page.locator('.article-body')).toContainText('不代表每日製鹽、固定DIY或現在可報名');
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]:not(:text-is("Google 地圖景點參考點"))')).toHaveCount(0);
 await page.locator('[data-trip-add="xiyuan-salt-museum"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="xiyuan-salt-museum"]')).toBeVisible();await page.locator('[data-stop="xiyuan-salt-museum"] [data-action="remove"]').click();await expect(page.locator('[data-stop="xiyuan-salt-museum"]')).toHaveCount(0);
 await page.goto('/attractions/xiyuan-salt-museum/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-xiyuan-salt-museum [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-xiyuan-salt-museum [data-pin]')).toHaveCount(0);

});
