import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/yu-dawei-museum.md','utf8').split('---')[1]);
test('Yu Dawei separates dated museum closures and current access',async({page})=>{
 await page.goto('/attractions/yu-dawei-museum/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('article.article-body a[href="https://www.google.com/maps/place/Mr.Yu+Da-wei+Memorial+Hall/@24.4430382,118.4289225,861m/data=!3m2!1e3!4b1!4m6!3m5!1s0x3414a4e685663355:0x827315c5410c6f26!8m2!3d24.4430333!4d118.4315028!16s%2Fm%2F0zbvjdw"]')).toBeVisible();
 await expect(page.locator('article.article-body')).toContainText('具名點位身份已由地圖核對');
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/yu-dawei-museum/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索俞大維先生紀念館','關於俞大維先生紀念館','基本資料','交通方式','路線地圖','人物、文物與數位保存','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('金門國家公園管理處');
 await expect(page.locator('.article-body')).toContainText('2026年9月30日版索引');
 await expect(page.locator('.article-body')).toContainText('除夕休館，作為官方一般時段及常規例外');
 expect(data.hours).toContain('除夕休館');
 expect(data.sources.some((s:any)=>s.url==='https://www.taiwan.nps.gov.tw/home/zh-tw/attractions/21158.html')).toBe(true);
 await expect(page.locator('.article-body')).not.toContainText('不把舊除夕或颱風個案直接當永久規則');
 await expect(page.locator('.article-body')).toContainText('2026年4月20–30日');
 await expect(page.locator('.article-body')).toContainText('8月24–28日');
 await expect(page.locator('.article-body')).toContainText('不因期限已過就保證全面恢復');
 await expect(page.locator('.article-body')).toContainText('不等於全部文物或土地產權證明');
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]:not(:text-is("Google 地圖景點參考點"))')).toHaveCount(0);
 await page.locator('[data-trip-add="yu-dawei-museum"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="yu-dawei-museum"]')).toBeVisible();await page.locator('[data-stop="yu-dawei-museum"] [data-action="remove"]').click();await expect(page.locator('[data-stop="yu-dawei-museum"]')).toHaveCount(0);
 await page.goto('/attractions/yu-dawei-museum/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-yu-dawei-museum [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-yu-dawei-museum [data-pin]')).toHaveCount(0);

});
