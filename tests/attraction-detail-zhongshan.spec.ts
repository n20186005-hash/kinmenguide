import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/zhongshan-forest.md','utf8').split('---')[1]);
test('Zhongshan separates visitor center and outdoor facilities',async({page})=>{
 await page.goto('/attractions/zhongshan-forest/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('article.article-body a[href="https://www.google.com/maps/place/%E4%B8%AD%E5%B1%B1%E7%B4%80%E5%BF%B5%E6%9E%97/@24.4392578,118.3547242,861m/data=!3m2!1e3!4b1!4m6!3m5!1s0x3414a243119dae61:0x8cd6aa488e85422b!8m2!3d24.4392578!4d118.3547242!16s%2Fg%2F155pp_2n"]')).toBeVisible();
 await expect(page.locator('article.article-body')).toContainText('具名點位身份已核');
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/zhongshan-forest/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索中山紀念林','關於中山紀念林','基本資料','交通方式','路線地圖','展示、林地與路線分級','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('遊客服務、設施工程及遊憩管理角色');
 await expect(page.locator('.article-body')).toContainText('中心規則不自動等於全戶外同一開閉時間');
 await expect(page.locator('.article-body')).toContainText('分一般級、挑戰級及危險級');
 await expect(page.locator('.article-body')).toContainText('2026年7月29日');
 await expect(page.locator('.article-body')).not.toContainText('2026年7月27日');
 expect(data.sources.some((s:any)=>s.title.includes('2026-07-29'))).toBe(true);
 await expect(page.locator('.article-body')).toContainText('不推今日仍停用、全林封園或已全面恢復');
 await expect(page.locator('.article-body')).toContainText('有設施不等隨到隨用');
 expect(data.hours).toContain('除夕休館');
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]:not(:text-is("Google 地圖景點參考點"))')).toHaveCount(0);
 await page.locator('[data-trip-add="zhongshan-forest"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="zhongshan-forest"]')).toBeVisible();await page.locator('[data-stop="zhongshan-forest"] [data-action="remove"]').click();await expect(page.locator('[data-stop="zhongshan-forest"]')).toHaveCount(0);
 await page.goto('/attractions/zhongshan-forest/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-zhongshan-forest [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-zhongshan-forest [data-pin]')).toHaveCount(0);

});
