import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/mashan-observation-post.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Mashan v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/mashan-observation-post/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/mashan-observation-post/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('LiCheng Shih / CC BY 2.0');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索馬山觀測所','關於馬山觀測所','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['沿著坑道，走到海的另一種視角','天氣會改變體驗','與金沙北線一起走','從觀測口看見戰地地理','觀察視野，也認識官澳']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager')).toContainText('金管處據點、歷史工程及服務發布角色已核');
  await expect(page.locator('.attraction-manager')).toContainText('完整現行管維與准入待核');
  await expect(page.locator('.article-cover img')).toHaveAttribute('alt','馬山觀測所的戰地建築與入口');
  await expect(page.locator('.attraction-basic')).toContainText('管理角色與狀態');
  expect(data.faq.find((f:any)=>f.question==='目前由誰維護遊客參觀範圍？').answer).toContain('未列入該公告所列駐點解說展示館');
  expect(data.faq.find((f:any)=>f.question==='目前由誰維護遊客參觀範圍？').answer).toContain('此分類僅歸該次春節公告，不推全年服務配置');
  await expect(page.getByRole('link',{name:'金管處・2026春節自導式景點服務公告',exact:true})).toHaveAttribute('href','https://www.kmnp.gov.tw/ch/titlelist/latest-news/4025');
  await expect(page.locator('.attraction-basic')).toContainText('082-352149');
  await expect(page.locator('.attraction-basic')).toContainText('082-330086');
  await expect(page.locator('article.article-body')).toContainText('不代表目前仍施工');
  await expect(page.locator('article.article-body')).toContainText('本站馬山播音站亦已另行核對其獨立具名地標與導航');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・馬山觀測所（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看馬山觀測所Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('890金門縣金沙鎮'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="mashan-observation-post"]')).toBeEnabled();
  await page.locator('[data-trip-add="mashan-observation-post"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'馬山觀測所',exact:true})).toBeVisible();
  await page.goto('/attractions/mashan-observation-post/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-mashan-observation-post [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});
