import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/zhushan-village.md','utf8').split('---')[1]);
test('Zhushan separates heritage scope and private admission',async({page})=>{
 await page.goto('/attractions/zhushan-village/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('article.article-body a[href="https://www.google.com/maps/place/Zhu+Shan+Village/data=!4m7!3m6!1s0x3414a1f4ebcf0b41:0x94ec577ef3575c8a!8m2!3d24.4014828!4d118.3205759!16s%2Fg%2F11h1d946q"]')).toBeVisible();
 await expect(page.locator('article.article-body')).toContainText('具名點位身份已核');
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/zhushan-village/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('rheins / CC BY 3.0');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索珠山聚落','關於珠山聚落','基本資料','交通方式','路線地圖','文資範圍與古厝活化','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['圍著大潭生長的村落','看宗祠、洋樓，再登小丘','留足步行時間','想在聚落過夜'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('文資主管');
 await expect(page.locator('.article-cover img')).toHaveAttribute('alt','珠山聚落的傳統廟宇、石鋪廣場與燕尾屋脊（2014年照片）');
 await expect(page.locator('.article-body')).toContainText('不證標租已成交、民宿已開業');
 await expect(page.locator('.article-body')).toContainText('珠山聚落部分為金門國家公園管理處管理');
 await expect(page.locator('.article-body')).toContainText('部分管理的具體區域與當期分工仍須另核，不外推全聚落');
 await expect(page.locator('.attraction-manager')).toContainText('國資網列聚落部分管理');
 await expect(page.locator('.article-body')).toContainText('不能把整聚落所有建物都稱同級古蹟');
 await expect(page.locator('.article-body')).toContainText('不把民宿茶水區當公共咖啡店');
 await expect(page.locator('.article-body')).toContainText('不探看住戶室內');
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]:not(:text-is("Google 地圖景點參考點"))')).toHaveCount(0);
 await page.locator('[data-trip-add="zhushan-village"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="zhushan-village"]')).toBeVisible();await page.locator('[data-stop="zhushan-village"] [data-action="remove"]').click();await expect(page.locator('[data-stop="zhushan-village"]')).toHaveCount(0);
 await page.goto('/attractions/zhushan-village/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-zhushan-village [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-zhushan-village [data-pin]')).toHaveCount(0);

});
