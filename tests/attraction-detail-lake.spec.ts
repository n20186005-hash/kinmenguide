import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/juguang-lake.md','utf8').split('---')[1]);
test('Juguang Lake keeps shore access separate from water activities and rescue exercises',async({page})=>{
 await page.goto('/attractions/juguang-lake/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('article.article-body a[href="https://www.google.com/maps/place/Ju+Guang+Lake/data=!4m7!3m6!1s0x3414a214f0d944ef:0xb6360d796a3e1ee5!8m2!3d24.4273874!4d118.3164672!16s%2Fg%2F1v41y1yq"]')).toBeVisible();
 await expect(page.locator('article.article-body')).toContainText('也不證明准入、停車或無障礙條件');
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/juguang-lake/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索莒光湖','關於莒光湖','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['市區南邊的一段留白','季節與光線各有表情','與親子遊戲分開選'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('尚待確認');
 await expect(page.locator('.article-body')).toContainText('湖畔散步不代表可下水');
 await expect(page.locator('.article-body')).toContainText('不能把演練或歷史活動當遊客可自行游泳、划船的證明');
 await expect(page.locator('.attraction-manager a')).toHaveCount(0);
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]:not(:text-is("Google 地圖景點參考點"))')).toHaveCount(0);
 await page.locator('[data-trip-add="juguang-lake"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="juguang-lake"]')).toBeVisible();await page.locator('[data-stop="juguang-lake"] [data-action="remove"]').click();await expect(page.locator('[data-stop="juguang-lake"]')).toHaveCount(0);
 await page.goto('/attractions/juguang-lake/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-juguang-lake [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-juguang-lake [data-pin]')).toHaveCount(0);

});
