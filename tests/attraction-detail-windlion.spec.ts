import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/wind-lion-cultural-shop.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Windlion preserves legacy topics, no invented photo, verified POI and closure warning', async ({page}) => {
  expect((await page.goto('/attractions/wind-lion-cultural-shop/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/wind-lion-cultural-shop/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover')).toHaveCount(0);
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索風獅爺文物坊（水頭42號）','關於風獅爺文物坊（水頭42號）','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['導航找水頭42號','從工藝認識風獅爺','和展示館一起走']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager')).toContainText('待確認');
  await expect(page.locator('.attraction-basic')).toContainText('金門縣金城鎮89342號');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('.article-header')).toContainText('Google地圖具名店家標記永久歇業');
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe(data.address); expect(place.hasMap).toBe(data.googleMapsUrl); expect(place.geo.latitude).toBe(24.4095025);
  await expect(page.locator('[data-trip-add="wind-lion-cultural-shop"]')).toBeEnabled();
  await page.locator('[data-trip-add="wind-lion-cultural-shop"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'風獅爺文物坊（水頭42號）',exact:true})).toBeVisible();
  await page.goto('/attractions/wind-lion-cultural-shop/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-wind-lion-cultural-shop [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('#map-point-attraction-wind-lion-cultural-shop')).toContainText('永久歇業');
});
