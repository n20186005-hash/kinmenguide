import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/shanhou-folk-culture-village.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Shanhou v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/shanhou-folk-culture-village/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/shanhou-folk-culture-village/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('Yenping Lee / CC BY-SA 4.0');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索山后民俗文化村','關於山后民俗文化村','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['慢慢看「十八間」','一條適合散步的東北線','拍照前，先尊重生活','十八間，如何組成一個聚落','從十八間大厝走到北岸','想在山后住一晚']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  expect(data.address).toBe('890金門縣金沙鎮');
  await expect(page.getByRole('link',{name:'山后65號民宿（山后海珠民宿）',exact:true}).first()).toHaveAttribute('href','/hotels/shanhou-65-bnb/');
  await expect(page.getByRole('link',{name:'蕃茄紅了古典館',exact:true}).first()).toHaveAttribute('href','/hotels/tomato-red-classical/');
  await expect(page.locator('.attraction-manager a')).toContainText('海珠堂展示維護');
  await expect(page.locator('.attraction-manager a')).toContainText('部分建築產權待釐清');
  await expect(page.locator('.attraction-basic')).toContainText('部分建築產權待釐清');
  await expect(page.locator('article.article-body')).not.toContainText('現行待複核');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://www.kmnp.gov.tw/ch/touristInfo/recreation-sites/11');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・金門山后民俗文化村（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看山后民俗文化村Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe(data.address); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="shanhou-folk-culture-village"]')).toBeEnabled();
  await page.locator('[data-trip-add="shanhou-folk-culture-village"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'山后民俗文化村',exact:true})).toBeVisible();
  await page.goto('/attractions/shanhou-folk-culture-village/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-shanhou-folk-culture-village [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});
