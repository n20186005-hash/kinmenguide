import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/chengshi-pavilion.md','utf8').split('---')[1]);
test('Chengshi v1.2 separates pavilion, preserves legacy and exact POI FAQ', async ({page})=>{
  expect((await page.goto('/attractions/chengshi-pavilion/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/chengshi-pavilion/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover')).toHaveCount(0);
  expect((await page.locator('article.article-body h2').allTextContents()).slice(0,10)).toEqual(['探索東崗誠實亭','關於東崗誠實亭','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','資料來源與行前提醒']);
  expect(await page.locator('article.article-body h2').allTextContents()).not.toContain('景點相冊');
  const titles=await page.locator('article.article-body h3').allTextContents();
  for(const t of ['南岸路線裡的一座亭','同樣的文字，不同的位置','亭邊休息，別走入採石區','附近怎麼安排']) expect(titles).toContain(t);
  await expect(page.locator('.attraction-manager a')).toContainText('亭本體現行管理／清潔維護待確認');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href',data.sources[0].url);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-basic')).toContainText('亭本體現行管理、清潔維護、產權與委外關係待確認');
  await expect(page.locator('article.article-body')).toContainText('歷史路跑報名費不是參觀門票');
  await expect(page.locator('article.article-body')).toContainText('紅土溝一營區L34入口的誠實標語是另一處');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・誠實亭（東崗具名地標）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看東崗誠實亭Google具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place=graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('894金門縣烈嶼鄉'); expect(place.hasMap).toBe(data.googleMapsUrl);
  expect(data.coordinates).toEqual({lat:24.4150669,lng:118.2424147});expect(data.googleMapsUrl).toContain('0x34149ed1f2cdab71:0xcf10f3e33a3125b0');
  await page.locator('[data-trip-add="chengshi-pavilion"]').click();await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:data.title,exact:true})).toBeVisible();
  await page.locator('[data-stop="chengshi-pavilion"] [data-action="remove"]').click();await expect(page.locator('[data-stop="chengshi-pavilion"]')).toHaveCount(0);
  await page.goto('/attractions/chengshi-pavilion/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');await expect(page.locator('#map-point-attraction-chengshi-pavilion [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('#map-point-attraction-chengshi-pavilion')).toContainText('不沿舊遊記追找下海小徑');
});
