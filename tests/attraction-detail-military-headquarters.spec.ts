import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/kinmen-military-headquarters.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Military headquarters v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/kinmen-military-headquarters/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/kinmen-military-headquarters/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('tomscoffin / CC BY 2.0');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索清金門鎮總兵署','關於清金門鎮總兵署','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['清代衙署與後浦的發展','跟著院落看展示','「浯江新莊」名稱怎麼找','白天看館，晚上走後浦']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toHaveCount(0);
  await expect(page.locator('.attraction-manager')).toContainText('現行完整分工待確認');
  await expect(page.locator('.article-header > div a[href*="tcmb.culture.tw"]')).toHaveText('文化部記憶庫・文資主管與駐點維護角色');
  await expect(page.locator('.article-header > div a[href*="tcmb.culture.tw"]')).toHaveAttribute('href','https://tcmb.culture.tw/zh-tw/detail?id=19911123000008&indexCode=BOCH_CountryCulture_11');
  await expect(page.locator('.attraction-basic')).toContainText('有界管理角色');
  await expect(page.locator('.attraction-basic')).toContainText('文化局為文資主管及文資網登記管理人');
  await expect(page.locator('.attraction-basic')).toContainText('觀光處為2024報告管理單位');
  await expect(page.locator('.attraction-basic')).not.toContainText('目前管理單位');
  expect(data.faq.find((q:any)=>q.answer.includes('文資主管')).answer).toContain('定期清潔維護');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・清金門鎮總兵署（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看清金門鎮總兵署Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe(data.address); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="kinmen-military-headquarters"]')).toBeEnabled();
  await page.locator('[data-trip-add="kinmen-military-headquarters"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'清金門鎮總兵署',exact:true})).toBeVisible();
  await page.goto('/attractions/kinmen-military-headquarters/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-kinmen-military-headquarters [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});
