import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/houlin-shooting-simulator.md','utf8').split('---')[1]);
test('Houlin preserves booking topics and distinguishes event fees from admission',async({page})=>{
 await page.goto('/attractions/houlin-shooting-simulator/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/houlin-shooting-simulator/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索后麟模擬靶場：步槍模擬射擊館','關於后麟模擬靶場：步槍模擬射擊館','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['舊營區裡的模擬體驗','年齡、預約與報到','票價與場次以當期公告為準','附近怎麼安排'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('尚待確認');
 await expect(page.locator('.article-body')).toContainText('2026特定比賽200元不是一般門票');
 await expect(page.locator('.article-body')).toContainText('082-363455');
 await expect(page.locator('.attraction-manager a')).toHaveCount(0);
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]')).toHaveCount(0);
 await page.locator('[data-trip-add="houlin-shooting-simulator"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="houlin-shooting-simulator"]')).toBeVisible();await page.locator('[data-stop="houlin-shooting-simulator"] [data-action="remove"]').click();await expect(page.locator('[data-stop="houlin-shooting-simulator"]')).toHaveCount(0);
 await page.goto('/attractions/houlin-shooting-simulator/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-houlin-shooting-simulator [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-houlin-shooting-simulator [data-pin]')).toHaveCount(0);

});
