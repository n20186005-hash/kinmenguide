import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/chen-jinglan-house.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('ChenJinglan v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/chen-jinglan-house/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/chen-jinglan-house/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('rheins / CC BY 3.0');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索陳景蘭洋樓','關於陳景蘭洋樓','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['從南洋回到故鄉的一棟洋樓','三個可以慢慢看的地方','怎麼到、怎麼順遊','帶長輩或遇雨的安排','洋樓前後的三個停留']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('金門縣金湖鎮公所');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://kinhu.kinmen.gov.tw/cp.aspx?n=5C09A32EDF7ADBDC');
  await expect(page.locator('article.article-body')).toContainText('私人所有權與個別商業服務不能畫上等號');
  await expect(page.locator('.attraction-basic')).toContainText('完整無障礙及各層動線未核實');
  await expect(page.locator('article.article-body')).toContainText('不保證固定班距或步行分鐘');
  await expect(page.locator('article.article-body')).toContainText('觀光署詳頁列成功1-1號');
  await expect(page.locator('article.article-body')).toContainText('地圖與附近公車位置有明顯錯置');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・陳景蘭洋樓（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看陳景蘭洋樓Google具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  expect(data.coordinates).toEqual({lat:24.4372225,lng:118.3900819});
  expect(data.googleMapsUrl).toContain('0x3414a4f000000001:0x37cdcf0757f67f08');
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('891金門縣金湖鎮'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="chen-jinglan-house"]')).toBeEnabled();
  await page.locator('[data-trip-add="chen-jinglan-house"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'陳景蘭洋樓',exact:true})).toBeVisible();
  await page.locator('[data-stop="chen-jinglan-house"] [data-action="remove"]').click();
  await expect(page.locator('[data-stop="chen-jinglan-house"]')).toHaveCount(0);
  await page.goto('/attractions/chen-jinglan-house/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-chen-jinglan-house [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});
