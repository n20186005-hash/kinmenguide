import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/huang-tingcan-house.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Huang Tingcan v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/huang-tingcan-house/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/huang-tingcan-house/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover')).toHaveCount(0);
  await expect(page.locator('.article-header')).toContainText('讀者2026-11-03回報');
  await expect(page.locator('.article-header')).toContainText('入口免費停車');
  await expect(page.locator('article.article-body')).toContainText('門前井水可汲取');
  await expect(page.locator('article.article-body')).toContainText('未提供到訪日期');
  await expect(page.locator('article.article-body')).toContainText('井水不作飲用水保證');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索黃廷參三落大厝（古厝小舖）','關於黃廷參三落大厝（古厝小舖）','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['先認清屋名與門牌','坐下來看三落老屋','私人空間的參訪禮節']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('古厝小舖經營者');
  await expect(page.locator('.attraction-basic')).toContainText('非產權認定');
  await expect(page.locator('article.article-body')).not.toContainText('現行待複核');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://kinmen.travel/zh-tw/shop/details/3834');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・黃廷參三落大厝（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看黃廷參三落大厝Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe(data.address); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="huang-tingcan-house"]')).toBeEnabled();
  await page.locator('[data-trip-add="huang-tingcan-house"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'黃廷參三落大厝（古厝小舖）',exact:true})).toBeVisible();
  await page.goto('/attractions/huang-tingcan-house/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-huang-tingcan-house [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});
