import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/wentai-pagoda.md','utf8').split('---')[1]);
test('Wentai separates dated tower sources and permitted access',async({page})=>{
 await page.goto('/attractions/wentai-pagoda/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('article.article-body a[href="https://www.google.com/maps/place/%E6%96%87%E8%87%BA%E5%AF%B6%E5%A1%94/@24.3987509,118.3034247,862m/data=!3m2!1e3!4b1!4m6!3m5!1s0x3414a21a013bba33:0x42cfc0396230c6a8!8m2!3d24.398746!4d118.306005!16s%2Fm%2F010lwchd"]')).toBeVisible();
 await expect(page.locator('article.article-body')).toContainText('具名點位身份已核');
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/wentai-pagoda/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('User:Vmenkov / CC BY-SA 3.0');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索文臺寶塔','關於文臺寶塔','基本資料','交通方式','路線地圖','國定古蹟與航海石塔','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['從海上認路的石塔','抬頭看塔，也低頭讀石刻','排進古城南線'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('國資網列管理人及維護角色');
 await expect(page.locator('.article-body')).toContainText('次年（1388）');
 await expect(page.locator('.article-body')).toContainText('（1387）建塔');
 await expect(page.locator('.article-body')).toContainText('不自行選定唯一年份');
 await expect(page.locator('.article-body')).toContainText('不是入塔、登頂、攀基座');
 await expect(page.locator('.article-body')).toContainText('文化局定期派員清除');
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]:not(:text-is("Google 地圖景點參考點"))')).toHaveCount(0);
 await page.locator('[data-trip-add="wentai-pagoda"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="wentai-pagoda"]')).toBeVisible();await page.locator('[data-stop="wentai-pagoda"] [data-action="remove"]').click();await expect(page.locator('[data-stop="wentai-pagoda"]')).toHaveCount(0);
 await page.goto('/attractions/wentai-pagoda/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-wentai-pagoda [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-wentai-pagoda [data-pin]')).toHaveCount(0);

});
