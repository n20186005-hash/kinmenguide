import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/landmine-museum.md','utf8').split('---')[1]);
test('Landmine museum distinguishes separate venues and qualifies sound access and management',async({page})=>{
 await page.goto('/attractions/landmine-museum/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('article.article-body a[href="https://www.google.com/maps/place/%E5%9C%B0%E9%9B%B7%E4%B8%BB%E9%A1%8C%E9%A4%A8/@24.4474024,118.2495636,861m/data=!3m2!1e3!4b1!4m6!3m5!1s0x3414991de35a4f9f:0x53a4b3a789f008f7!8m2!3d24.4473975!4d118.2521439!16s%2Fg%2F12q4q64r0"]')).toBeVisible();
 await expect(page.locator('article.article-body')).toContainText('具名點位身份已由地圖核對');
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/landmine-museum/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索地雷主題館','關於地雷主題館','基本資料','交通方式','路線地圖','戰地與展示','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['在地下空間理解地雷歷史','聲光效果先有心理準備','和鐵漢堡合併安排','附近怎麼安排'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('現行整館管理及權屬待核');
 await expect(page.locator('.article-body')).toContainText('不能套其遊程資格、時段與管理資料到本館');
 await expect(page.locator('.article-body')).toContainText('不保證有地上替代展區或全程無階梯');
 await expect(page.locator('.article-body')).toContainText('不碰、不撿、不自行處理');
 await expect(page.locator('.article-body')).toContainText('不直接把堡票價套作館票');
 await expect(page.locator('.article-body')).toContainText('連通坑道實際如何計收未核');
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]:not(:text-is("Google 地圖景點參考點"))')).toHaveCount(0);
 await page.locator('[data-trip-add="landmine-museum"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="landmine-museum"]')).toBeVisible();await page.locator('[data-stop="landmine-museum"] [data-action="remove"]').click();await expect(page.locator('[data-stop="landmine-museum"]')).toHaveCount(0);
 await page.goto('/attractions/landmine-museum/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-landmine-museum [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-landmine-museum [data-pin]')).toHaveCount(0);

});
