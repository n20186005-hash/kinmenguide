import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/jinshui-school.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Jinshui v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/jinshui-school/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/jinshui-school/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('lienyuan lee / CC BY 3.0');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索金水國小展示館','關於金水國小展示館','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['一所學校，裝著出洋者對家鄉的期待','不只拍門面，也看看教室','水頭半天怎麼走','實用提醒']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toHaveText('內政部國家公園署金門國家公園管理處');
  await expect(page.locator('.attraction-basic')).toContainText('展示館管理維護；非所有權認定');
  await expect(page.locator('article.article-body')).not.toContainText('現行待複核');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://www.kmnp.gov.tw/ch/titlelist/latest-news/4319');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google 地圖・金水學校展示館（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看金水學校展示館 Google 地圖地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe(data.address); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="jinshui-school"]')).toBeEnabled();
  await page.locator('[data-trip-add="jinshui-school"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'金水國小展示館',exact:true})).toBeVisible();
  await page.goto('/attractions/jinshui-school/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-jinshui-school [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});
