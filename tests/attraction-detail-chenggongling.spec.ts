import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/chenggongling-wind-lion.md','utf8').split('---')[1]);
test('Chenggongling v1.2 separates private installation, preserves legacy and exact POI FAQ', async ({page})=>{
  expect((await page.goto('/attractions/chenggongling-wind-lion/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/chenggongling-wind-lion/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover')).toHaveCount(0);
  expect((await page.locator('article.article-body h2').allTextContents()).slice(0,10)).toEqual(['探索成功嶺風獅爺（私人裝置）','關於成功嶺風獅爺（私人裝置）','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','資料來源與行前提醒']);
  expect(await page.locator('article.article-body h2').allTextContents()).not.toContain('景點相冊');
  const titles=await page.locator('article.article-body h3').allTextContents();
  for(const t of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近']) expect(titles).toContain(t);
  await expect(page.locator('.attraction-manager a')).toContainText('現行私人管理／維護者及開放待確認');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href',data.sources[0].url);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-basic')).toContainText('2017報導僅為歷史紀錄');
  await expect(page.locator('article.article-body')).toContainText('沒有票價資料不等於免費開放');
  await expect(page.locator('article.article-body')).toContainText('不是臺中成功嶺營區');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・成功嶺風獅爺（私人裝置地標）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看成功嶺風獅爺Google具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place=graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('891金門縣金湖鎮瓊徑路891號310之1號'); expect(place.hasMap).toBe(data.googleMapsUrl);
  expect(data.coordinates).toEqual({lat:24.44236,lng:118.389498});expect(data.googleMapsUrl).toContain('0x3414a3007aa6f985:0x2cdc9cfbb57b7f9c');
  await page.locator('[data-trip-add="chenggongling-wind-lion"]').click();await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:data.title,exact:true})).toBeVisible();
  await page.locator('[data-stop="chenggongling-wind-lion"] [data-action="remove"]').click();await expect(page.locator('[data-stop="chenggongling-wind-lion"]')).toHaveCount(0);
  await page.goto('/attractions/chenggongling-wind-lion/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');await expect(page.locator('#map-point-attraction-chenggongling-wind-lion [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('#map-point-attraction-chenggongling-wind-lion')).toContainText('現況及對外開放未確認');
});
