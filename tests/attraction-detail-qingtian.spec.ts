import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/qingtian-hall.md','utf8').split('---')[1]);
test('Qingtian separates application approval and military access',async({page})=>{
 await page.goto('/attractions/qingtian-hall/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/qingtian-hall/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索太武山擎天廳','關於太武山擎天廳','基本資料','交通方式','路線地圖','工程與軍事參訪','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('金防部複審/入營查驗');
 await expect(page.locator('.article-body')).toContainText('申請表另見團體7至30日字樣');
 await expect(page.locator('.article-body')).toContainText('不據此推外籍可參訪');
 await expect(page.locator('.article-body')).toContainText('未核准不自行到營門');
 await expect(page.locator('.article-body')).toContainText('至少提前7日完成，可申請未來60日內行程');
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.getByRole('link',{name:'Google 地圖具名景點參考點',exact:true})).toHaveCount(1);
 await page.locator('[data-trip-add="qingtian-hall"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="qingtian-hall"]')).toBeVisible();await page.locator('[data-stop="qingtian-hall"] [data-action="remove"]').click();await expect(page.locator('[data-stop="qingtian-hall"]')).toHaveCount(0);
 await page.goto('/attractions/qingtian-hall/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-qingtian-hall [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-qingtian-hall [data-pin]')).toHaveCount(0);

});
