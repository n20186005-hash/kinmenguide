import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/guanao-wind-lions.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Guanao v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/guanao-wind-lions/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/guanao-wind-lions/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('官澳社區發展協會（官方圖片來源標示） / 政府網站資料開放宣告（保留既有依據；第三人權利待確認）');
  await expect(page.locator('.article-cover a')).toHaveAttribute('href','/credits/#place-guanao-wind-lions');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索官澳風獅爺','關於官澳風獅爺','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('現行各尊管理維護單位待確認');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://kinmen.travel/zh-tw/travel/attraction/549');
  await expect(page.locator('article.article-body')).toContainText('其他三尊Google具名地標未於本批逐一核對');
  await expect(page.locator('.attraction-basic')).toContainText('75公分官方落點近乎重疊雄獅');
  await expect(page.locator('article.article-body')).toContainText('不同欄位及新舊石獅敘事需分別閱讀');
  expect(readFileSync('PHOTO-CREDITS.md','utf8').split('## place-guanao-wind-lions')[1].split('## ')[0]).toContain('官澳社區發展協會');
  for (const id of ['549','548','1652','1653']) expect(await page.locator('article.article-body a').evaluateAll(as=>as.map(a=>a.getAttribute('href')))).toContain('https://kinmen.travel/zh-tw/travel/attraction/'+id);
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・官澳風獅爺雄獅（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看官澳風獅爺雄獅Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(data.coordinates).toEqual({lat:24.5212886,lng:118.4135364});
  expect(data.googleMapsUrl).toContain('0x3414bb9f27b90eb9:0x6ab0467e1a70bd45');
  expect(place.address.streetAddress).toBe('890金門縣金沙鎮'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="guanao-wind-lions"]')).toBeEnabled();
  await page.locator('[data-trip-add="guanao-wind-lions"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'官澳風獅爺',exact:true})).toBeVisible();
  await page.goto('/attractions/guanao-wind-lions/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-guanao-wind-lions [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});

test('Guanao credit identifies provided image and keeps third-party rights unresolved', async ({page}) => {
  await page.goto('/credits/#place-guanao-wind-lions');
  const credit = page.locator('#place-guanao-wind-lions');
  await expect(credit).toContainText('官澳社區發展協會');
  await expect(credit).toContainText('第三人權利待確認');
  await expect(credit.getByRole('link',{name:'授權條款'})).toHaveAttribute('href','https://kinmen.travel/zh-tw/gwoia');
});
