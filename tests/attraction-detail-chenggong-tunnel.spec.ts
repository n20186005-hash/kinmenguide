import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/chenggong-tunnel.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('ChenggongTunnel v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/chenggong-tunnel/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/chenggong-tunnel/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索成功海防坑道','關於成功海防坑道','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('金門縣金湖鎮公所');
  await expect(page.locator('.attraction-basic')).toContainText('當期坑道時段待確認');
  await expect(page.locator('.attraction-basic')).toContainText('其他官方資料未提供明確費用資訊');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://kinhu.kinmen.gov.tw/cp.aspx?n=5C09A32EDF7ADBDC');
  await expect(page.locator('article.article-body')).toContainText('不授予任何封閉坑口');
  await expect(page.locator('article.article-body')).toContainText('不保證坑道入口有車位');
  await expect(page.locator('article.article-body')).toContainText('公所現行觀光導覽列中興亭到出海口段');
  await expect(page.locator('article.article-body')).toContainText('不宣稱今天仍演出');
  await expect(page.locator('article.article-body')).toContainText('114.12（2025年12月）進度截點');
  await expect(page.locator('article.article-body')).toContainText('並非具體完工日，也不證明當日全線、各坑口或支線開放');
  await expect(page.locator('article.article-body')).toContainText('當期安排及特殊服務費用請向金湖鎮公所確認');
  expect(data.admission).not.toContain('費用欄不一致');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・成功海防坑道（具名坑道地標）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看成功海防坑道Google具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  expect(data.coordinates).toEqual({lat:24.4364354,lng:118.3884952});
  expect(data.googleMapsUrl).toContain('0x3414a37f3e500f3b:0x27096b08bf493676');
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('891金門縣金湖鎮環島南路三段'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="chenggong-tunnel"]')).toBeEnabled();
  await page.locator('[data-trip-add="chenggong-tunnel"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'成功海防坑道',exact:true})).toBeVisible();
  await page.locator('[data-stop="chenggong-tunnel"] [data-action="remove"]').click();
  await expect(page.locator('[data-stop="chenggong-tunnel"]')).toHaveCount(0);
  await page.goto('/attractions/chenggong-tunnel/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-chenggong-tunnel [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('#map-point-attraction-chenggong-tunnel')).toContainText('不由歷史軍管描述推現況');
});
