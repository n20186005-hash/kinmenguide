import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/chenggong-wind-lion.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('ChenggongLion v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/chenggong-wind-lion/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/chenggong-wind-lion/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索成功風獅爺','關於成功風獅爺','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toHaveCount(0);
  await expect(page.locator('.attraction-manager')).toContainText('現行完整權責待確認');
  await expect(page.locator('.attraction-basic')).toContainText('歷史管理／照料記錄');
  await expect(page.locator('article.article-body')).toContainText('2013/01/25瀏覽紀錄不是現任登記日期');
  await expect(page.locator('article.article-body')).toContainText('正義社區志工隊於5月21日');
  await expect(page.locator('article.article-body')).toContainText('不合併推作今日祭典日程或參與許可');
  await expect(page.locator('.attraction-basic')).toContainText('Google地址行政區與官方不一致');
  await expect(page.locator('article.article-body')).toContainText('不預設石像旁有車位');
  await expect(page.locator('article.article-body')).toContainText('不認定石獅位於金城');
  await expect(page.locator('article.article-body')).toContainText('住家門口私人藝術裝置');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・成功風獅爺（村落石獅地標）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看成功風獅爺Google具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  expect(data.coordinates).toEqual({lat:24.4372471,lng:118.3895366});
  expect(data.googleMapsUrl).toContain('0x3414a300171a0f2d:0xd27716c273f938d8');
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('891金門縣金城鎮金城'); expect(place.hasMap).toBe(data.googleMapsUrl);
  expect(place.address).not.toHaveProperty('addressLocality');
  await expect(page.locator('[data-trip-add="chenggong-wind-lion"]')).toBeEnabled();
  await page.locator('[data-trip-add="chenggong-wind-lion"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'成功風獅爺',exact:true})).toBeVisible();
  await page.locator('[data-stop="chenggong-wind-lion"] [data-action="remove"]').click();
  await expect(page.locator('[data-stop="chenggong-wind-lion"]')).toHaveCount(0);
  await page.goto('/attractions/chenggong-wind-lion/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/attractions/chenggong-tunnel/');
  const other = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]).find(n=>n['@type']==='TouristAttraction');
  expect(other.address.addressLocality).toBe('金湖');
  expect(other.address.streetAddress).toBe('891金門縣金湖鎮環島南路三段');
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-chenggong-wind-lion [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('#map-point-attraction-chenggong-wind-lion')).toContainText('Google地址行政區有差異');
});
