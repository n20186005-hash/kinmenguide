import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/jieshou-pavilion.md','utf8').split('---')[1]);
test('Jieshou keeps management unverified without relying on an ambiguous report',async({page})=>{
 await page.goto('/attractions/jieshou-pavilion/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/jieshou-pavilion/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('烈嶼鄉公所 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索介壽亭與介壽公園','關於介壽亭與介壽公園','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['龍蟠山腰的六角亭','一段短程散步','雨後注意階梯','附近怎麼安排'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('尚待確認');
 await expect(page.locator('.article-body')).not.toContainText('2018年縣府報告曾記鄉公所管理');
 await expect(page.locator('.article-body')).toContainText('鄉公所發布景點介紹不等於已證實由其管理或擁有');
 await expect(page.locator('.attraction-manager a')).toHaveCount(0);
 await expect(page.locator('article a[href*="research.kinmen.gov.tw"]')).toHaveCount(0);
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps/place/"]')).toHaveCount(1);
 await expect(page.locator('.article-body')).toContainText('不是入口、准入、停車或無障礙證明');
 await page.locator('[data-trip-add="jieshou-pavilion"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="jieshou-pavilion"]')).toBeVisible();await page.locator('[data-stop="jieshou-pavilion"] [data-action="remove"]').click();await expect(page.locator('[data-stop="jieshou-pavilion"]')).toHaveCount(0);
 await page.goto('/attractions/jieshou-pavilion/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-jieshou-pavilion [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-jieshou-pavilion [data-pin]')).toHaveCount(0);

});
