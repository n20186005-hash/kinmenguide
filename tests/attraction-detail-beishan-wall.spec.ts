import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/beishan-broadcasting-wall.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('BeishanWall v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/beishan-broadcasting-wall/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/beishan-broadcasting-wall/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toHaveCount(1);
  expect(await page.locator('.article-cover img').evaluate((i:HTMLImageElement)=>i.complete&&i.naturalWidth>0)).toBe(true);
  await expect(page.locator('.article-cover figcaption')).toContainText('照片不代表目前開放或可入內');
  await expect(page.locator('.article-cover a')).toHaveAttribute('href','/credits/#place-beishan-broadcasting-wall');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索北山播音牆','關於北山播音牆','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['48個喇叭留下的歷史','什麼時候去、怎麼聽']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('現行整處管理單位待確認');
  await expect(page.locator('.attraction-basic')).toContainText('播放六個參考時段');
  await expect(page.locator('article.article-body')).toContainText('約2024年官方戶外教育場域盤點');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・北山播音牆（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看北山播音牆Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  expect(data.coordinates).toEqual({lat:24.4888998,lng:118.3130939});
  expect(data.googleMapsUrl).toContain('0x3414a30078f437c1:0x85295e17f8c62bff');
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('892金門縣金寧鄉湖埔村'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="beishan-broadcasting-wall"]')).toBeEnabled();
  await page.locator('[data-trip-add="beishan-broadcasting-wall"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'北山播音牆',exact:true})).toBeVisible();
  await page.goto('/attractions/beishan-broadcasting-wall/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-beishan-broadcasting-wall [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});
