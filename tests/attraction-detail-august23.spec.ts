import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/august-23-battle-museum.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('August23 v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/august-23-battle-museum/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/august-23-battle-museum/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('Jane9306 / CC BY-SA 4.0');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索八二三戰史館','關於八二三戰史館','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('內政部國家公園署金門國家公園管理處');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://www.kmnp.gov.tw/ch/titlelist/latest-news/1228');
  await expect(page.locator('.attraction-basic')).toContainText('實際恢復待確認');
  await expect(page.locator('a[href="https://www.kmnp.gov.tw/ch/titlelist/latest-news/4553"]')).toBeVisible();
  await expect(page.locator('article.article-body')).toContainText('2025年7月11日重新開幕');
  await expect(page.locator('article.article-body')).toContainText('僅預計9月15日復開');
  await expect(page.locator('.attraction-basic')).toContainText('891金門縣金湖鎮山外里安民村1之11號');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・八二三戰史館（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看八二三戰史館Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  expect(data.coordinates).toEqual({lat:24.4431889,lng:118.4324028});
  expect(data.googleMapsUrl).toContain('0x3414a4e696340b61:0xffe16c56eed67eda');
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('891金門縣金湖鎮山外里安民村1之11號'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="august-23-battle-museum"]')).toBeEnabled();
  await page.locator('[data-trip-add="august-23-battle-museum"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'八二三戰史館',exact:true})).toBeVisible();
  await page.goto('/attractions/august-23-battle-museum/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-august-23-battle-museum [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('#map-point-attraction-august-23-battle-museum')).toContainText('實際恢復與當日開放待確認');
});
