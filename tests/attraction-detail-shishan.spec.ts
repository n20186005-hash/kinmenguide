import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/shishan-howitzer-front.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Shishan v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/shishan-howitzer-front/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/shishan-howitzer-front/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('Ping an Chang / CC BY-SA 4.0');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索獅山砲陣地','關於獅山砲陣地','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['施工期間先查場次','陣地和表演分開規劃','親子參觀重點','從坑道配置理解砲陣地','和北岸怎麼搭']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('金門縣政府（法規主管機關');
  await expect(page.locator('.attraction-basic')).toContainText('不證明已完成甄用或人員到任');
  await expect(page.locator('.attraction-basic')).toContainText('現場管理與委外安排待確認');
  await expect(page.locator('.attraction-basic')).toContainText('原預定11-30完工');
  await expect(page.locator('.attraction-basic')).toContainText('週一、四停演');
  await expect(page.locator('.attraction-basic')).toContainText('15:50、16:50場次暫停');
  await expect(page.locator('article.article-body')).toContainText('實際完工及全面開放另行公告');
  await expect(page.locator('article.article-body')).not.toContainText('現行待複核');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://law.kinmen.gov.tw/LawContent.aspx?id=GL000762&kw=');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・獅山砲陣地（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看獅山砲陣地Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('890金門縣金沙鎮何斗里陽沙路376號'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="shishan-howitzer-front"]')).toBeEnabled();
  await page.locator('[data-trip-add="shishan-howitzer-front"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'獅山砲陣地',exact:true})).toBeVisible();
  await page.goto('/attractions/shishan-howitzer-front/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-shishan-howitzer-front [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('#map-point-attraction-shishan-howitzer-front')).toContainText('每週一、四砲操停演');
});
