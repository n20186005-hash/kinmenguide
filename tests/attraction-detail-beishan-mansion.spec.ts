import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/beishan-old-mansion.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('BeishanMansion v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/beishan-old-mansion/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/beishan-old-mansion/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  const cover = page.locator('.article-cover img');
  await expect(cover).toHaveCount(1);
  await expect(cover).toHaveAttribute('alt', '2019年北山古洋樓的雙層殘牆、彈痕與相連閩式建築');
  expect(await cover.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
  await expect(page.locator('.article-cover figcaption')).toContainText('2019年北山古洋樓歷史外觀');
  await expect(page.locator('.article-cover figcaption')).toContainText('不代表目前住宿空間、入內範圍或開放狀態');
  await expect(page.locator('.article-cover figcaption')).toContainText('Rueichung / CC BY-SA 4.0');
  await expect(page.locator('.article-cover a')).toHaveAttribute('href', '/credits/#place-beishan-old-mansion');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索北山古洋樓','關於北山古洋樓','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['一棟樓有兩段歷史','外觀可以看，住宿區要尊重']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('內政部國家公園署金門國家公園管理處');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://www.kmnp.gov.tw/ch/planlist/conservation-achievement-reports/614');
  await expect(page.locator('.attraction-basic')).toContainText('住宿區與洋樓殘跡不保證開放');
  await expect(page.locator('article.article-body')).toContainText('2019年歷史外觀照片已補入頁面');
  await expect(page.locator('article.article-body')).toContainText('不證明目前住宿、入內或開放狀態');
  await expect(page.locator('article.article-body')).toContainText('雙落大厝、不含洋樓');
  await expect(page.locator('article.article-body')).toContainText('但未說明住宿區或左護龍的進入規則');
  await expect(page.locator('article.article-body')).toContainText('非今日開放現況或結構安全鑑定');
  await expect(page.locator('article.article-body')).toContainText('依縣旅遊介紹，洋樓於1937年增建');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・北山古洋樓背包客棧（同建築住宿POI）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看北山古洋樓同建築住宿POI'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  expect(data.coordinates).toEqual({lat:24.479211,lng:118.31256});
  expect(data.googleMapsUrl).toContain('0x3414a2bb15e54485:0xfb936bd27e642f75');
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('892金門縣金寧鄉古寧村北山46-5號'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="beishan-old-mansion"]')).toBeEnabled();
  await page.locator('[data-trip-add="beishan-old-mansion"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'北山古洋樓',exact:true})).toBeVisible();
  await page.goto('/attractions/beishan-old-mansion/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-beishan-old-mansion [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('#map-point-attraction-beishan-old-mansion')).toContainText('住宿POI');
});
