import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/houtou-wind-lions.md','utf8').split('---')[1]);
test('Houtou distinguishes two historic statues without inferring present access',async({page})=>{
 await page.goto('/attractions/houtou-wind-lions/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/houtou-wind-lions/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索后頭風獅爺','關於后頭風獅爺','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['兩尊風獅爺一起看','從造型讀地方信仰','不移動衣飾與供品','附近怎麼安排'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('尚待確認');
 await expect(page.locator('.article-body')).toContainText('2010年尋回');
 await expect(page.locator('.article-body')).toContainText('1991年重塑');
 await expect(page.locator('.attraction-manager a')).toHaveCount(0);
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]')).toHaveCount(0);
 await page.locator('[data-trip-add="houtou-wind-lions"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="houtou-wind-lions"]')).toBeVisible();await page.locator('[data-stop="houtou-wind-lions"] [data-action="remove"]').click();await expect(page.locator('[data-stop="houtou-wind-lions"]')).toHaveCount(0);
 await page.goto('/attractions/houtou-wind-lions/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-houtou-wind-lions [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-houtou-wind-lions [data-pin]')).toHaveCount(0);

});
