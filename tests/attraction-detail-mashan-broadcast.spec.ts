import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/mashan-broadcasting-station.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Mashan broadcast v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/mashan-broadcasting-station/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/mashan-broadcasting-station/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('koika / CC BY-SA 3.0');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索馬山播音站','關於馬山播音站','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['用聲音跨越海面的年代','播音站與觀測所差在哪裡','怎麼排金沙北線','保留對場所的尊重','播音站與觀測所各看什麼']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('現行整站管理待確認');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://www.kmnp.gov.tw/ch/titlelist/latest-news/4025');
  await expect(page.locator('.attraction-basic')).toContainText('Google列08:00起');
  await expect(page.locator('article.article-body')).toContainText('兩者不是同一個地標');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・馬山播音站（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看馬山播音站Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(data.coordinates).toEqual({lat:24.5287029,lng:118.4084773});
  expect(data.googleMapsUrl).toContain('0x3414bb9a126743e5:0xf96009af0f9cf03a');
  expect(place.address.streetAddress).toBe('890金門縣金沙鎮'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="mashan-broadcasting-station"]')).toBeEnabled();
  await page.locator('[data-trip-add="mashan-broadcasting-station"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'馬山播音站',exact:true})).toBeVisible();
  await page.goto('/attractions/mashan-broadcasting-station/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-mashan-broadcasting-station [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});
