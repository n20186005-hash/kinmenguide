import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/national-quemoy-university.md','utf8').split('---')[1]);
test('NQU separates visitor vehicle and library admission',async({page})=>{
 await page.goto('/attractions/national-quemoy-university/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/national-quemoy-university/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索國立金門大學','關於國立金門大學','基本資料','交通方式','路線地圖','校園與教育','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('國立金門大學');
 await expect(page.locator('.article-body')).toContainText('不進宿舍、教室或研究空間');
 await expect(page.locator('.article-body')).toContainText('不是全校訪客許可');
 await expect(page.locator('.article-body')).toContainText('2026年9月30日修正');
 await expect(page.locator('.article-body')).toContainText('閱覽室週一至五08:00–22:30');
 await expect(page.locator('.article-body')).toContainText('期中/期末考週除外');
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps/place/"]')).toHaveCount(1);
 await expect(page.locator('.article-body')).toContainText('不是訪客入口、准入、停車或無障礙證明');
 await page.locator('[data-trip-add="national-quemoy-university"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="national-quemoy-university"]')).toBeVisible();await page.locator('[data-stop="national-quemoy-university"] [data-action="remove"]').click();await expect(page.locator('[data-stop="national-quemoy-university"]')).toHaveCount(0);
 await page.goto('/attractions/national-quemoy-university/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-national-quemoy-university [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-national-quemoy-university [data-pin]')).toHaveCount(0);

});
