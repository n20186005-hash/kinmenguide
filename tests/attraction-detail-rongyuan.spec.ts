import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const data=JSON.parse(readFileSync('src/content/attractions/rongyuan.md','utf8').split('---')[1]);
test('Rongyuan separates tree records historic works and indoor admission',async({page})=>{
 await page.goto('/attractions/rongyuan/');
 await expect(page.locator('h1')).toHaveCount(1);
 await expect(page.locator('article.article-body a[href="https://www.google.com/maps/place/Banyan+Park/@24.4439357,118.4294338,861m/data=!3m2!1e3!4b1!4m6!3m5!1s0x3414a4e41d9d4eab:0x13c1fa7864f04e55!8m2!3d24.4439308!4d118.4320141!16s%2Fg%2F1tjmb8r8"]')).toBeVisible();
 await expect(page.locator('article.article-body')).toContainText('具名點位身份已核');
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/rongyuan/');
 await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
 await expect(page.locator('.article-cover img')).toBeVisible();
 await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
 const hs=await page.locator('article.article-body h2').allTextContents();
 expect(hs).not.toContain('景點相冊');
 expect(hs.slice(0,10)).toEqual(['探索榕園與慰廬','關於榕園與慰廬','基本資料','交通方式','路線地圖','人文與老樹','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程','查核日期與參觀提醒']);
 for(const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近'])await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(1);
 await expect(page.locator('.attraction-manager')).toContainText('當期完整管理/權屬分工待核');
 await expect(page.locator('.article-body')).toContainText('不證明整園管理');
 await expect(page.locator('.article-body')).toContainText('不保證每項設施當日可用');
 await expect(page.locator('.article-body')).toContainText('每日08:30–17:00');
 await expect(page.locator('.article-body')).toContainText('2025-05-26更新景點頁');
 await expect(page.locator('.article-body')).toContainText('非今日確認');
 await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveCount(0);
 const visible=await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
 expect(visible).toEqual(data.faq);
 const graph=(await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
 expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
 const place=graph.find(n=>n['@type']==='TouristAttraction');expect(place.address).toBeUndefined();expect(place.hasMap).toBeUndefined();expect(place.geo).toBeUndefined();expect(data.coordinates).toBeUndefined();
 await expect(page.locator('article a[href*="maps.app.goo.gl"]')).toHaveCount(0);
 await expect(page.locator('article a[href*="google.com/maps"]:not(:text-is("Google 地圖景點參考點"))')).toHaveCount(0);
 await page.locator('[data-trip-add="rongyuan"]').click();await page.goto('/trip/');await expect(page.locator('[data-stop="rongyuan"]')).toBeVisible();await page.locator('[data-stop="rongyuan"] [data-action="remove"]').click();await expect(page.locator('[data-stop="rongyuan"]')).toHaveCount(0);
 await page.goto('/attractions/rongyuan/');expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/map/');await expect(page.locator('#map-point-attraction-rongyuan [data-map-location-link]')).toHaveCount(0);
 await expect(page.locator('#map-point-attraction-rongyuan [data-pin]')).toHaveCount(0);

});
