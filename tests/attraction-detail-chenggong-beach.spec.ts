import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/chenggong-beach.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('ChenggongBeach v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/chenggong-beach/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/chenggong-beach/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('rheins / CC BY 3.0');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索成功沙灘','關於成功沙灘','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager')).toContainText('成功海邊景點人員排班角色已核');
  await expect(page.locator('.attraction-basic')).toContainText('非整片海灘管理、清潔、產權或軍界證明');
  expect(data.faq.find((f:any)=>f.question==='由哪個單位管理？').answer).toContain('不證當日人員到勤、救生服務、水域開放');
  await expect(page.locator('.attraction-basic')).toContainText('不含坑道時段');
  await expect(page.locator('.attraction-basic')).toContainText('其他官方資料未提供明確費用資訊');
  await expect(page.locator('.attraction-basic')).toContainText('官方合併景點2026-03-31資料列免費');
  await expect(page.locator('article.article-body')).toContainText('當期安排及特殊服務費用請向金湖鎮公所確認');
  await expect(page.locator('article.article-body')).toContainText('當期安排及特殊服務費用請向金湖鎮公所確認');
  expect(data.admission).not.toContain('顯示不一致');
  await expect(page.getByRole('link',{name:'金湖鎮公所・2026-10-27職掌表（成功海邊景點人員排班角色）',exact:true})).toHaveAttribute('href','https://kinhu.kinmen.gov.tw/cp.aspx?n=5C09A32EDF7ADBDC');
  await expect(page.locator('article.article-body')).toContainText('不是當天可走岸線');
  await expect(page.locator('article.article-body')).toContainText('不可預設沙灘入口有停車位');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・成功沙灘（具名海灘地標）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看成功沙灘Google具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  expect(data.coordinates).toEqual({lat:24.4352043,lng:118.387407});
  expect(data.googleMapsUrl).toContain('0x3414a4f000000001:0x55b291bb1cb9854e');
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('891金門縣金湖鎮'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="chenggong-beach"]')).toBeEnabled();
  await page.locator('[data-trip-add="chenggong-beach"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'成功沙灘',exact:true})).toBeVisible();
  await page.locator('[data-stop="chenggong-beach"] [data-action="remove"]').click();
  await expect(page.locator('[data-stop="chenggong-beach"]')).toHaveCount(0);
  await page.goto('/attractions/chenggong-beach/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-chenggong-beach [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.locator('#map-point-attraction-chenggong-beach')).toContainText('不代表當天可游泳');
});
