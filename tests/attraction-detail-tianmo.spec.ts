import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const raw = readFileSync('src/content/attractions/tianmo-mountain.md', 'utf8');
const data = JSON.parse(raw.split('---')[1]);
test('Tianmo v1.2 preserves legacy topics, photo, map POI and exact FAQ schema', async ({page}) => {
  expect((await page.goto('/attractions/tianmo-mountain/'))?.status()).toBe(200);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href','https://kinmenguide.com/attractions/tianmo-mountain/');
  await expect(page.locator('[data-attraction-detail]')).toHaveCount(1);
  await expect(page.locator('.article-cover img')).toBeVisible();
  await expect(page.locator('figcaption')).toContainText('金門縣政府觀光處 / 政府網站資料開放宣告');
  const heads = await page.locator('article.article-body h2').allTextContents();
  expect(heads.slice(0,9)).toEqual(['探索天摩山步道','關於天摩山步道','基本資料','交通方式','路線地圖','人文生態','遊客資訊與常見問答','行前規劃與深度遊覽','周邊景點與順路行程']);
  expect(heads).not.toContain('景點相冊');
  const topics = await page.locator('article.article-body h3').allTextContents();
  for (const title of ['這裡值得看什麼','怎麼安排參觀','把下一站排在附近']) expect(topics).toContain(title);
  await expect(page.locator('.attraction-basic')).toContainText(data.address);
  await expect(page.locator('.attraction-manager a')).toContainText('現行步道管理分工待確認');
  await expect(page.locator('.attraction-manager a')).toHaveAttribute('href','https://www.kmnp.gov.tw/ch/titlelist/latest-news/1166');
  await expect(page.locator('.attraction-basic')).toContainText('2024公告小客車位6格');
  await expect(page.locator('article.article-body')).toContainText('2025年保育公告針對天摩山既有營區');
  await expect(page.locator('article.article-body')).toContainText('步道僅緊急或公務車輛駛入');
  await expect(page.locator('article.article-body')).toContainText('未獨立核實它就是登山口、停車場或山頂');
  await expect(page.locator('.attraction-basic')).toContainText('890金門縣金沙鎮官嶼里沙青路34號');
  await expect(page.getByRole('link',{name:'查看位置',exact:true})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'Google地圖・天摩山（具名景點）'})).toHaveAttribute('href',data.googleMapsUrl);
  await expect(page.getByRole('link',{name:'查看天摩山Google地圖具名地標'})).toHaveAttribute('href',data.googleMapsUrl);
  const visible = await page.locator('article.article-body details').evaluateAll(ds=>ds.map(d=>({question:d.querySelector('summary')?.textContent,answer:d.querySelector('p')?.textContent})));
  expect(visible).toEqual(data.faq);
  const graph = (await page.locator('script[type="application/ld+json"]').allTextContents()).flatMap(t=>JSON.parse(t)['@graph']??[]);
  expect(graph.find(n=>n['@type']==='FAQPage').mainEntity.map((q:any)=>({question:q.name,answer:q.acceptedAnswer.text}))).toEqual(data.faq);
  expect(data.coordinates).toEqual({lat:24.5267481,lng:118.4181221});
  expect(data.googleMapsUrl).toContain('0x3414bbbd4ada6df3:0x3b87962e691e395f');
  const place = graph.find(n=>n['@type']==='TouristAttraction');
  expect(place.address.streetAddress).toBe('890金門縣金沙鎮官嶼里沙青路34號'); expect(place.hasMap).toBe(data.googleMapsUrl);
  await expect(page.locator('[data-trip-add="tianmo-mountain"]')).toBeEnabled();
  await page.locator('[data-trip-add="tianmo-mountain"]').click();
  await page.goto('/trip/');
  await expect(page.getByRole('heading',{name:'天摩山步道',exact:true})).toBeVisible();
  await page.goto('/attractions/tianmo-mountain/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('/map/');
  await expect(page.locator('#map-point-attraction-tianmo-mountain [data-map-location-link]')).toHaveAttribute('href',data.googleMapsUrl);
});
